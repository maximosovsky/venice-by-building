import assert from 'node:assert/strict';
import fs from 'node:fs';
import zlib from 'node:zlib';
import { chromium } from 'playwright';
import { buildPalazzoMask } from '../web/palazzo-highlight.js';
const base = process.argv[2] || 'http://127.0.0.1:8873/';
const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-unsafe-swiftshader','--use-angle=swiftshader','--no-sandbox']});
try {
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[], shaderErrors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('404'))shaderErrors.push(m.text());});
 await page.goto(base+'?lang=ru&shot',{waitUntil:'networkidle',timeout:120000});
 await page.waitForFunction(()=>document.body.dataset.ready==='1'&&window.__dbg,null,{timeout:120000});
 const cfg=await page.evaluate(async()=> (await fetch('data/venezia.json')).json());
 const wiki=await page.evaluate(async()=> (await fetch('data/wiki.json')).json());
 const names=await page.evaluate(async()=> (await fetch('data/names.json')).json());
 const bytes=await page.evaluate(async()=> [...new Uint8Array(await (await fetch('data/attrs.bin')).arrayBuffer())]);
 const raw=zlib.gunzipSync(Buffer.from(bytes));
 const expected=buildPalazzoMask(new DataView(raw.buffer,raw.byteOffset,raw.byteLength),cfg,wiki,names);
 const mask=await page.evaluate(()=>[...window.__dbg.uniforms.uPalazzo.value.image.data]);
 assert.deepEqual(mask.slice(0,expected.length),[...expected]);
 assert.ok(mask.slice(expected.length).every(v=>v===0));
 await page.locator('[data-mode="2"]').click();
 assert.equal(await page.evaluate(()=>window.__dbg.uniforms.uMode.value),2);
 await page.waitForTimeout(1800);
 const gid=[...expected].findIndex(v=>v===1);
 const rendered=await page.evaluate(gid=>{let found=false;window.__dbg.scene.traverse(m=>{if(!m.userData.draw)return;const a=m.userData.draw.uniforms.uAttr.value.image.data;for(let i=3;i<a.length;i+=8)if(a[i]===gid)found=true;});return found;},gid);
 assert.equal(rendered,true,'matched Palazzo has rendered geometry');
 await page.evaluate(gid=>{const d=window.__dbg,b=d.building(gid);d.controls.target.set(b.x,0,b.z);d.camera.position.set(b.x+140,180,b.z+190);d.controls.update();},gid);
 await page.waitForTimeout(1300);
 const screenshot='C:/Users/1/AppData/Local/hermes/cache/scratch/venice-palazzo-heritage.png';
 await page.screenshot({path:screenshot});
 await page.locator('[data-mode="0"]').click();
 assert.equal(await page.evaluate(()=>window.__dbg.uniforms.uMode.value),0);
 await page.waitForTimeout(200);
 await page.locator('[data-mode="2"]').click();
 await page.waitForTimeout(200);
 await page.evaluate(()=>window.__dbg.pick(720,500));
 assert.deepEqual(errors,[]);assert.deepEqual(shaderErrors,[]);
 console.log(JSON.stringify({base,count:[...expected].filter(Boolean).length,rendered,errors,shaderErrors,screenshot}));
} finally {await browser.close();}
